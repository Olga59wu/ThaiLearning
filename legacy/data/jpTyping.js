// 🎧 一鍵下載所有離線音檔
export const downloadOfflineAudio = async (onProgress) => {
    const audioUrls = [];

    // 💡 自動處理 ja_ 與 zh_，並過濾特殊字元
    const getAudioUrl = (text, type = 'ja') => {
        const langCode = type === 'ja' ? 'ja' : 'zh';
        const safeText = text.replace(/[\/（）\s〜]/g, '_');
        return `./audio/JP/${langCode}_${safeText}.mp3`;
    };

    Object.values(VOCAB_CATEGORIES).forEach(category => {
        category.forEach(word => {
            if (word.ja) audioUrls.push(getAudioUrl(word.ja, 'ja'));
            if (word.zh) audioUrls.push(getAudioUrl(word.zh, 'zh'));
        });
    });

    const uniqueUrls = [...new Set(audioUrls)];
    let successCount = 0;

    for (let i = 0; i < uniqueUrls.length; i++) {
        try {
            const response = await fetch(uniqueUrls[i]);
            if (response.ok) {
                successCount++;
            } else {
                console.warn(`找不到音檔: ${uniqueUrls[i]}`);
            }
        } catch (e) {
            console.error(`下載出錯: ${uniqueUrls[i]}`, e);
        }

        if (onProgress) {
            onProgress(i + 1, uniqueUrls.length);
        }
    }

    return successCount;
};